# Marcas de tilde: lista de (dx, dy) relativos a la esquina superior izquierda del glifo
_ACCENTS: Dict[str, Tuple[str, List[Tuple[int, int]]]] = {
    "Á": ("A", [(3, -2), (2, -1)]), "É": ("E", [(3, -2), (2, -1)]),
    "Í": ("I", [(3, -2), (2, -1)]), "Ó": ("O", [(3, -2), (2, -1)]),
    "Ú": ("U", [(3, -2), (2, -1)]), "Ü": ("U", [(1, -2), (3, -2)]),
    "Ñ": ("N", [(1, -1), (2, -2), (3, -1)]),
}

GLYPHS: Dict[str, List[Tuple[int, int]]] = {}
for _line in _RAW.strip().splitlines():
    _ch, *_rows = _line.split("|") if not _line.startswith("|") else ["|"] + _line[2:].split("|")
    if _line.startswith("||"):
        _ch, _rows = "|", _line[3:].split("|")
    GLYPHS[_ch] = [(x, y) for y, row in enumerate(_rows) for x, c in enumerate(row) if c == "#"]
GLYPHS[" "] = []
for _acc, (_base, _marks) in _ACCENTS.items():
    GLYPHS[_acc] = GLYPHS[_base] + _marks
FALLBACK = GLYPHS["█"]


def supports(text: str) -> bool:
    """¿Todos los caracteres (en mayúscula) existen en la fuente?"""
    return all(ch.upper() in GLYPHS or ch == "\n" for ch in text)


def glyph(ch: str) -> List[Tuple[int, int]]:
    return GLYPHS.get(ch.upper(), FALLBACK)
